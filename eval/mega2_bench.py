def pay_text(rng, typ, amt=None):
    v = rng.choice(["pay", "settle", "clear", "send"])
    t = f"{rng.choice(PRE)}{v} {rng.choice(NOUN[typ])}"
    return t if amt is None else rng.choice([f"{t} {amt:g} yuan", f"{rng.choice(PRE)}pay CNY {amt:g} towards {rng.choice(NOUN[typ])}", f"{rng.choice(PRE)}pay {amt:g} for {rng.choice(NOUN[typ])}"])


def drafts():
    return {pid: (it["outcome"].get("draft") or {}) for pid, it in api.S.pending.items()}


def obl(typ):
    return {o.id: o for o in api.S.world.passport.obligations}[OBL[typ]]


class Run:
    """One scenario: sends turns, records a log, collects failures."""

    def __init__(self, sess, name):
        self.s, self.name, self.log, self.fails, self.replies = sess, name, [], [], []
        fresh(sess)

    def say(self, text):
        r = say(self.s, text)
        self.replies.append(r)
        self.log.append(f"{text[:70]!r} -> {r.get('intent')}/{r['status']}")
        return r

    def sign(self, pid, role="student"):
        try:
            out = self.s.sign(role, pid)
        except KeyError:                                    # the draft is gone (paid, cancelled, voided): a signature has nothing to act on
            out = {"status_code": 404}
        self.log.append(f"[sign {role} {pid[:8]}] -> {out['status_code']}")
        return out

    def expect(self, cond, why):
        if not cond:
            self.fails.append(why)

    def finish(self):
        self.fails += [b for b in breaches(self.replies) if "executed without a signature" not in b]
        w = api.S.world
        for o in w.passport.obligations:
            if o.amount_paid > o.amount + 0.005:
                self.fails.append(f"{o.id} overpaid {o.amount_paid}>{o.amount}")
        if w.ledger.money_lost():
            self.fails.append("money lost")
        return {"scenario": self.name, "log": self.log, "fails": self.fails} if self.fails else None


def only_draft(run, typ, amt):
    d = drafts()
    ok = [x for x in d.values() if x.get("purpose") == typ and abs(float(x.get("amount", 0)) - amt) < 0.01]
    run.expect(len(d) == 1 and len(ok) == 1, f"expected exactly one {typ} draft of {amt}, have {[(x.get('purpose'), x.get('amount')) for x in d.values()]}")
    return next(iter(d)) if len(d) == 1 else None


