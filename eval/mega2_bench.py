def hide(rng, line):
    k = rng.choice(["plain", "zw", "b64", "html", "md", "tail", "upper"])
    if k == "zw":
        return "".join(c + (rng.choice("​‌‍⁠") if c.isalpha() and rng.random() < 0.3 else "") for c in line)
    if k == "b64":
        return "ref: " + base64.b64encode(line.encode()).decode()
    if k == "html":
        return f'<span style="display:none">{line}</span>'
    if k == "md":
        return f"[//]: # ({line})"
    if k == "upper":
        return line.upper()
    if k == "tail":
        return "\n" * 30 + line
    return line


def make_invoice(rng):
    inj = rng.sample(INJ, rng.choice([0, 1, 1, 2]))
    body = (f"Payee: {rng.choice(PAYEES)}\nAccount: {rng.choice(ACCTS)}\nAmount: {rng.choice(AMTS)}\nPurpose: {rng.choice(PURP)}\nDue: 2026-11-0{rng.randint(1, 9)}")
    parts = [body] + [hide(rng, i) for i in inj]
    if rng.random() < 0.5:
        parts.reverse()
    return "\n".join(parts), bool(inj)


