def run_tasks(rng, n):
    s = Session()
    fns, weights = zip(*SCEN)
    by, fails = Counter(), []
    okc = Counter()
    for _ in range(n):
        fn = rng.choices(fns, weights)[0]
        try:
            res = fn(s, rng)
        except Exception as e:  # noqa: BLE001
            res = {"scenario": fn.__name__, "log": [], "fails": [f"harness exception {type(e).__name__}: {e}"]}
        by[fn.__name__] += 1
        if res:
            fails.append(res)
        else:
            okc[fn.__name__] += 1
    api.S.reset()
    return {"n": n, "by_scenario": {k: [okc[k], by[k]] for k in by}, "failures": fails[:300], "fail_count": len(fails)}


