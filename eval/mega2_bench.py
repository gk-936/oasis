def sc_full(s, rng):
    typ = rng.choice(list(OBL))
    r = Run(s, "full_payment")
    for _ in range(rng.choice([0, 0, 1])):
        r.say(rng.choice(QUESTIONS))
    a = r.say(pay_text(rng, typ))
    pid = only_draft(r, typ, OWED[typ])
    if pid:
        r.expect(r.sign(pid)["status_code"] == 200, "signing failed")
        o = obl(typ)
        r.expect(o.status == "paid" and abs(o.amount_paid - OWED[typ]) < 0.01, f"{typ} not paid in full ({o.status} {o.amount_paid})")
        r.expect(len(api.S.world.proofs) == 1, "no proof")
        r.expect(r.sign(pid)["status_code"] != 200, "a used draft could be signed again")
    return r.finish()


def sc_partial(s, rng):
    typ = rng.choice(["rent", "tuition", "deposit"])
    amt = float(rng.choice([500, 1000, 1500, 2000, 2500, 3000, 4000, 5000]))
    r = Run(s, "part_payment")
    a = r.say(pay_text(rng, typ, amt))
    if a["status"] == "needs_confirmation":
        if rng.random() < 0.2:                                  # the student says no: nothing may remain
            r.say("no")
            r.expect(not drafts(), "draft remains after 'no' to a part payment")
            return r.finish()
        r.say(rng.choice(["yes", "ok", "yes please", "confirm"]))
    pid = only_draft(r, typ, amt)
    if pid:
        r.expect(r.sign(pid)["status_code"] == 200, "signing failed")
        o = obl(typ)
        r.expect(abs(o.amount_paid - amt) < 0.01 and o.status != "paid", f"part payment wrong: paid {o.amount_paid} status {o.status}")
    return r.finish()


def sc_fraction(s, rng):
    typ = rng.choice(["rent", "tuition"])
    r = Run(s, "half_payment")
    a = r.say(rng.choice([f"pay half of {rng.choice(NOUN[typ])}", f"i want to pay half my {typ}", f"pay a quarter of the {typ}"]))
    frac = 0.25 if "quarter" in r.log[-1] else 0.5
    if a["status"] == "needs_confirmation":
        r.say("yes")
    pid = only_draft(r, typ, OWED[typ] * frac)
    if pid:
        r.expect(r.sign(pid)["status_code"] == 200, "signing failed")
        r.expect(abs(obl(typ).amount_paid - OWED[typ] * frac) < 0.01, "wrong fraction paid")
    return r.finish()


def sc_correct(s, rng):
    typ = rng.choice(["rent", "tuition", "deposit"])
    n = float(rng.choice([1000, 1200, 2600, 3000, 4500, 5000]))
    r = Run(s, "correction")
    r.say(pay_text(rng, typ))
    old = next(iter(api.S.pending), None)
    a = r.say(rng.choice([f"actually make it {n:g}", f"change the amount to {n:g}", f"i meant {n:g}", f"the amount should be {n:g}", f"no, make it {n:g}"]))
    if a["status"] == "needs_confirmation":
        r.say("yes")
    pid = only_draft(r, typ, n)
    if old and pid:
        r.expect(pid != old and old not in api.S.pending, "the old draft is still alive after a correction")
        r.expect(r.sign(old)["status_code"] != 200 if old not in api.S.pending else True, "the voided draft could be signed")
        r.expect(r.sign(pid)["status_code"] == 200, "signing the corrected draft failed")
        r.expect(abs(obl(typ).amount_paid - n) < 0.01, f"paid {obl(typ).amount_paid} not the corrected {n}")
    return r.finish()


