JUNK = ["", "null", "[]", "{}", '{"message": 5}', '{"message": null}', '{"message": ["a"]}', '{"message": {"a": 1}}', "{" * 5000, '{"message": "' + "A" * 200000 + '"}',
        '{"message": "\\u0000\\u0000"}', '{"message": "' + "你" * 20000 + '"}', "\xff\xfe", "<xml/>", "a=b&c=d"]
TRICKS = ["../../etc/passwd", "..%2f..%2fenv", "%00", "' OR 1=1 --", "<script>alert(1)</script>", "A" * 5000, "{{7*7}}", "${jndi:ldap://x}", "../.env", "intent_x'; DROP TABLE x;--"]
GET_PATHS = ["/api/proof/{}", "/api/proof/{}/verify", "/api/trust-pass/check/{}", "/api/evidence-passport/check/{}", "/api/plan/{}"]


def leaked(text):
    return [x for x in SECRETS if x in text]


def run_abuse(rng, n):
    s = Session()
    findings, calls, notes = [], 0, Counter()

    def note(what, resp=None, extra=None):
        findings.append({"what": what, "status": getattr(resp, "status_code", None), "extra": extra})

    def call(c, method, url, **kw):
        nonlocal calls
        calls += 1
        try:
            r = c.request(method, url, **kw)
        except Exception as e:  # noqa: BLE001
            note(f"exception {type(e).__name__} on {method} {url[:60]}")
            return None
        if r.status_code >= 500:
            note(f"5xx on {method} {url[:60]}", r)
        lk = leaked(r.text)
        if lk and url != "/api/auth/login":
            note(f"secret in response of {method} {url[:60]}: {lk}", r)
        return r

    for i in range(n):
        kind = rng.choice(["junk_chat", "junk_post", "tricks", "forged_cookie", "logout_reuse", "two_sessions", "no_session", "role_endpoints", "brute", "replay"])
        api.S.login_limiter._hits.clear()                   # the harness itself must be able to log in; lockout is tested in "brute"
        fresh(s)
        if kind == "junk_chat":
            for body in rng.sample(JUNK, 3):
                call(s.student, "POST", "/api/chat", content=body, headers={"content-type": rng.choice(["application/json", "text/plain", "application/x-www-form-urlencoded"])})
        elif kind == "junk_post":
            path = rng.choice(["/api/intake", "/api/approve", "/api/fx/convert", "/api/plan", "/api/rate-target", "/api/spending/add", "/api/device/register", "/api/pay-again"])
            call(s.student, "POST", path, content=rng.choice(JUNK), headers={"content-type": "application/json"})
        elif kind == "tricks":
            for t in rng.sample(TRICKS, 4):
                for p in rng.sample(GET_PATHS, 2):
                    r = call(s.student, "GET", p.format(quote(t, safe="")))
                    if r is not None and r.status_code == 200 and ("root:" in r.text or "OASIS_" in r.text):
                        note("path trick returned file content", r)
        elif kind == "forged_cookie":
            c = TestClient(api.app, raise_server_exceptions=False)
            for name, val in list(s.student.cookies.items()):
                forged = rng.choice([val[:-3] + "abc", val + "x", val.upper(), "", "a." + val, val.replace(".", "")[:20]])
                c.cookies.set(name, forged)
            r = call(c, "POST", "/api/chat", json={"message": "pay my rent"})
            if r is not None and r.status_code == 200:
                note("forged cookie accepted", r)
            r = call(c, "GET", "/api/state")
            if r is not None and r.status_code == 200:
                note("forged cookie read state", r)
        elif kind == "logout_reuse":
            c = Session._login("student")
            old = dict(c.cookies)
            call(c, "POST", "/api/auth/logout")
            c2 = TestClient(api.app, raise_server_exceptions=False)
            for k, v in old.items():
                c2.cookies.set(k, v)
            r = call(c2, "GET", "/api/state")
            if r is not None and r.status_code == 200:
                note("a logged-out session cookie still works", r)
        elif kind == "two_sessions":
            a, b = Session._login("student"), Session._login("student")
            call(a, "POST", "/api/chat", json={"message": "pay my rent"})
            n0 = len(api.S.pending)
            for m in rng.sample(["yes", "cancel", "never mind", "undo", "actually make it 100"], 2):
                call(b, "POST", "/api/chat", json={"message": m})
            if len(api.S.pending) != n0:
                notes["same_principal_cross_session_edit"] += 1           # same student on two devices: cancelling or re-amounting a draft is allowed
            if api.S.world.proofs or any(o.amount_paid for o in api.S.world.passport.obligations):
                note("another session's chat paid something")
        elif kind == "no_session":
            c = TestClient(api.app, raise_server_exceptions=False)
            before = (len(api.S.pending), len(api.S.world.proofs), len(api.S.world.audit.entries))
            for p in rng.sample(["/api/chat", "/api/approve", "/api/intake", "/api/fx/convert", "/api/reset", "/api/pay-again"], 3):
                r = call(c, "POST", p, json={"message": "pay my rent", "pending_id": "x", "text": "x", "amount": 1})
                if r is not None and r.status_code not in (401, 403, 429):
                    note(f"anonymous POST {p} got {r.status_code}", r)
            if before != (len(api.S.pending), len(api.S.world.proofs), len(api.S.world.audit.entries)):
                note("an anonymous call changed state")
        elif kind == "role_endpoints":
            for p in ("/api/approvers",):                       # the parent-only surface: the student session must not sign or consent as the parent
                r = call(s.student, "POST", "/api/plan/x/consent", json={"step": 0, "signature": "00", "key_id": s.keys["parent"]})
                if r is not None and r.status_code == 200:
                    note("student session consented as the parent", r)
            before = len(api.S.world.proofs)
            r = call(s.parent, "POST", "/api/chat", json={"message": "pay my rent"})
            if r is not None and r.status_code == 200 and len(api.S.world.proofs) != before:
                note("parent chat paid something")
        elif kind == "brute":
            c = TestClient(api.app, raise_server_exceptions=False)
            lim, fails, locked = api.S.login_limiter.limit, 0, False
            for k in range(rng.randint(3, 25)):
                r = call(c, "POST", "/api/auth/login", json={"role": rng.choice(["student", "parent", "judge", "admin", ""]), "passcode": rng.choice(["", "1234", "student", "parent-demo ", "' OR 1=1", "A" * 3000])})
                if r is None:
                    continue
                if r.status_code == 200:
                    note("a wrong passcode logged in", r)
                elif r.status_code == 429:
                    locked = True
                else:
                    fails += 1
            if fails > lim + 1 and not locked:
                note(f"no lockout after {fails} failed logins (limit {lim})")
            r = call(c, "POST", "/api/auth/login", json={"role": "student", "passcode": "student-demo"})
            if locked and r is not None and r.status_code == 200:
                note("the right passcode logged in during a lockout", r)
            api.S.login_limiter._hits.clear()
        elif kind == "replay":
            r = say(s, "pay my rent")
            pid = r.get("pending_id")
            if pid:
                out = s.sign("student", pid)
                for _ in range(rng.randint(1, 3)):
                    out2 = s.sign("student", pid) if pid in {p["id"] for p in s.student.get("/api/state").json()["pending"]} else {"status_code": 404}
                    if out2["status_code"] == 200:
                        note("replayed approval accepted")
                if len(api.S.world.proofs) > 1:
                    note("more than one proof from one draft")
    api.S.reset()
    return {"n": n, "calls": calls, "design_notes": dict(notes), "findings": findings[:200], "finding_count": len(findings)}


# ------------------------------------------------------------------ report
def md_tasks(rep):
    t = rep["tasks"]
    ok = sum(v[0] for v in t["by_scenario"].values())
    L = ["| Scenario | Passed / run |", "|---|---|"] + [f"| {k} | {v[0]} / {v[1]} |" for k, v in sorted(t["by_scenario"].items())]
    L += ["", f"**Task scenarios passed: {ok} / {t['n']}**", "", "### Failures (first 25)", ""]
    for f in t["failures"][:25]:
        L.append(f"- `{f['scenario']}`: {f['fails']} | " + " ; ".join(f["log"][:6]))
    return L + ([] if t["failures"] else ["None."])


def md_inject(rep):
    t = rep["inject"]
    L = [f"Poisoned invoices sent: {t['n']:,} (channels {t['by_channel']}). Breaches: **{t['finding_count']}**.", "", f"Reply statuses: {t['statuses']}", ""]
    return L + [f"- {f['channel']}: {f['problems']} | {f['text'][:120]!r}" for f in t["findings"][:25]] + ([] if t["findings"] else ["None."])


def md_abuse(rep):
    t = rep["abuse"]
    L = [f"Abuse rounds: {t['n']:,}, HTTP calls: {t['calls']:,}. Findings: **{t['finding_count']}**.", ""]
    return L + [f"- {f['what']} (status {f['status']}) {f['extra'] or ''}" for f in t["findings"][:30]] + ([] if t["findings"] else ["None."])


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--seed", type=int, default=5)
    ap.add_argument("--tasks", type=int, default=3000)
    ap.add_argument("--inject", type=int, default=3000)
    ap.add_argument("--abuse", type=int, default=1500)
    ap.add_argument("--only", choices=["tasks", "inject", "abuse"])
    a = ap.parse_args()
    if api.S.world.llm.name != "offline-deterministic":
        raise SystemExit("refusing to run: the model is not offline")
    rng = random.Random(a.seed)
    t0 = time.time()
    rep = {"meta": {"run": datetime.now().strftime("%Y-%m-%d %H:%M"), "seed": a.seed, "caveat": CAVEAT}}
    bad = 0
    for part, fn, n, md in (("tasks", run_tasks, a.tasks, md_tasks), ("inject", run_inject, a.inject, md_inject), ("abuse", run_abuse, a.abuse, md_abuse)):
        if a.only and a.only != part:
            continue
        res = fn(random.Random(rng.random()), n)
        rep[part] = res
        bad += res.get("fail_count", 0) + res.get("finding_count", 0)
        rep["meta"]["seconds"] = round(time.time() - t0)
        head = [f"# Mega stress test 2: {part} (offline)", "", f"Run: {rep['meta']['run']} | seed {a.seed} | LLM: offline-deterministic | {rep['meta']['seconds']}s", "", f"**Caveat.** {CAVEAT}", ""]
        text = "\n".join(head + md({part: res, **{k: res for k in ()}} if False else {part: res}))
        REPORTS.mkdir(exist_ok=True)
        (REPORTS / f"mega2_{part}.json").write_text(json.dumps({"meta": rep["meta"], part: res}, indent=1, ensure_ascii=False), encoding="utf-8")
        (REPORTS / f"mega2_{part}.md").write_text(text, encoding="utf-8")
        print(text.encode("ascii", "replace").decode(), flush=True)
    return 0 if bad == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
